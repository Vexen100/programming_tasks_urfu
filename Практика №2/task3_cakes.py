def print_pack_report(cakes_number):
    """
    Генерирует отчёт о возможных способах расфасовки пирожных.
    
    Функция перебирает все числа от cakes_number до 1 в порядке убывания
    и выводит информацию о том, как можно расфасовать указанное количество пирожных:
    
    - если число делится и на 3, и на 5, выводит "расфасуем по 3 или по 5"
    - если делится только на 5, выводит "расфасуем по 5"
    - если делится только на 3, выводит "расфасуем по 3"
    - в остальных случаях выводит "не заказываем"
    
    Примеры:
        30 - расфасуем по 3 или по 5
        10 - расфасуем по 5
        9 - расфасуем по 3
        14 - не заказываем!
    
    Аргументы:
        cakes_number: целое положительное число (количество пирожных)
    """
    for num in range(cakes_number, 0, -1):
        if num % 3 == 0 and num % 5 == 0:
            print(f'{num} - расфасуем по 3 или по 5')
        elif num % 3 == 0:
            print(f'{num} - расфасуем по 3')
        elif num % 5 == 0:
            print(f'{num} - расфасуем по 5')
        else:
            print(f'{num} - не заказываем!')